class Solution:
    def getSum(self, a: int, b: int) -> int:
        #正数的补码与原码相同，负数的补码为其原码除符号位外所有位取反（这就是反码了）
        # 然后最低位加1。
        #^按位异或运算符，当两个对应的二进位相异时，结果为1
        #&按位运算符，参与运算的两个值，如果相应位都为1，则该位的结果为1，否则为0
        #~按位取反运算符，对数据的每个二进制位取反，即把1变为0，把0变为1
        MASK1 = 4294967296  # 2^32
        MASK2 = 2147483648  # 2^31
        MASK3 = 2147483647  # 2^31-1

        a %= MASK1
        b %= MASK1
        while b != 0:
            carry = ((a & b) << 1) % MASK1#<< 1 表示将数值在二进制下向左移动一位（相当于乘以 2）。相同的生成carry，然后进位
            a = (a ^ b) % MASK1 #这个是不进位的那些位置的操作
            b = carry
        if a & MASK2:  # 负数&=MASK2,正数=0
            return ~((a ^ MASK2) ^ MASK3)
        else:  # 正数
            return a